#!/usr/bin/env python3
"""WeFax Auto Plan: plan.json (this folder) into the firmware and the web server.

  python3 -I tools/wefax_plan/plan_to_c.py [--check]

writes src/wefax/plan_default.h, the plan the app follows when /mnt/wefax/plan.json is not there, and
webserver/src/x6100_webserver/static/wefax_plan.json, the same plan for the web WeFax page's Bulletin. A plan that
is not JSON, or has a slot the radio would skip, stops it before either is written. --check writes nothing: it fails
when either is not what plan.json makes (the host test runs it).

From OlivLoze's fork (F4OLI), its plan_to_c.py.

SPDX-License-Identifier: LGPL-2.1-or-later
"""
import json
import os
import re
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TOP = os.path.join(HERE, "..", "..")
PLAN = os.path.join(HERE, "plan.json")
HEADER = os.path.join(TOP, "src", "wefax", "plan_default.h")
WEB = os.path.join(TOP, "webserver", "src", "x6100_webserver", "static", "wefax_plan.json")


def check(plan):
    """The rules src/wefax/plan.c reads a slot by: a slot that breaks one would be left out on the radio"""
    slots = plan.get("slots")
    if not isinstance(slots, list) or not slots:
        sys.exit("plan.json: no slots")
    for s in slots:
        if not re.fullmatch(r"([01]\d|2[0-3]):[0-5]\d", s.get("t", "")):
            sys.exit(f"plan.json: bad time in {s}")
        if not 100000 <= s.get("hz", 0) <= 30000000:
            sys.exit(f"plan.json: bad frequency in {s}")
        if not 60 <= s.get("dur", 690) <= 3600:
            sys.exit(f"plan.json: bad length in {s}")
        if len(s.get("prod", "")) >= 48 or len(s.get("st", "")) >= 16 or " " in s.get("st", ""):
            sys.exit(f"plan.json: a name too long, or a station with a space, in {s}")
    for b in plan.get("bulletin", []):
        if len(b.get("name", "")) >= 24 or not b.get("match") or len(b["match"]) > 6:
            sys.exit(f"plan.json: bad Bulletin kind {b}")


def main():
    src = open(PLAN).read()
    check(json.loads(src))
    lines = "\n".join('    "%s\\n"' % line.replace("\\", "\\\\").replace('"', '\\"') for line in src.splitlines())
    header = ("/* Generated by tools/wefax_plan/plan_to_c.py from tools/wefax_plan/plan.json: edit that, not this */\n\n"
              "static const char plan_default_json[] =\n%s;\n" % lines)
    if "--check" in sys.argv[1:]:
        for path, want in ((HEADER, header), (WEB, src)):
            if not os.path.exists(path) or open(path).read() != want:
                sys.exit(f"{os.path.relpath(path, TOP)} is not plan.json's: run tools/wefax_plan/plan_to_c.py")
        print("plan_default.h and wefax_plan.json are plan.json's")
        return
    with open(HEADER, "w") as f:
        f.write(header)
    shutil.copyfile(PLAN, WEB)
    print(os.path.relpath(HEADER, TOP), os.path.relpath(WEB, TOP))


if __name__ == "__main__":
    main()
